fn cached_power(exponent: i32) -> (Fp, i32) {
    let approximate = (-(exponent + 87) as f64 * 0.30102999566398114) as i32;
    let mut index = ((approximate + 348) / 8) as usize;
    loop {
        let (fraction, cached_exponent) = POWERS[index];
        let current = exponent + cached_exponent + 64;
        if current < -60 {
            index += 1;
        } else if current > -32 {
            index -= 1;
        } else {
            return (
                Fp {
                    fraction,
                    exponent: cached_exponent,
                },
                -348 + index as i32 * 8,
            );
        }
    }
}

fn round_digit(digits: &mut [u8], delta: u64, mut remainder: u64, step: u64, fraction: u64) {
    while remainder < fraction
        && delta - remainder >= step
        && (remainder + step < fraction || fraction - remainder > remainder + step - fraction)
    {
        *digits.last_mut().expect("at least one generated digit") -= 1;
        remainder += step;
    }
}

/// Generate the exact significant digits and decimal shift used by fpconv.
/// Caller has already handled zero, NaN/infinities, sign, and integer fast path.
pub(super) fn digits(n: f64) -> (String, i32) {
    debug_assert!(n.is_finite() && n > 0.0);
    let bits = n.to_bits();
    let hidden = 1u64 << 52;
    let binary_exponent = ((bits >> 52) & 0x7ff) as i32;
    let w = Fp {
        fraction: (bits & (hidden - 1)) + if binary_exponent == 0 { 0 } else { hidden },
        exponent: if binary_exponent == 0 {
            -1074
        } else {
            binary_exponent - 1075
        },
    };
    let upper = Fp {
        fraction: (w.fraction << 1) + 1,
        exponent: w.exponent - 1,
    }
    .normalized();
    let lower_shift = if w.fraction == hidden { 2 } else { 1 };
    let mut lower = Fp {
        fraction: (w.fraction << lower_shift) - 1,
        exponent: w.exponent - lower_shift,
    };
    lower.fraction <<= lower.exponent - upper.exponent;
    lower.exponent = upper.exponent;
    let (cached, decimal_exponent) = cached_power(upper.exponent);
    let w = w.normalized().multiply(cached);
    let mut upper = upper.multiply(cached);
    let mut lower = lower.multiply(cached);
    lower.fraction += 1;
    upper.fraction -= 1;
    let distance = upper.fraction - w.fraction;
    let mut delta = upper.fraction - lower.fraction;
    let shift = -upper.exponent;
    let one = 1u64 << shift;
    let mut integer = upper.fraction >> shift;
    let mut fraction = upper.fraction & (one - 1);
    let mut digits = Vec::with_capacity(18);
    let mut kappa = 10;
    let mut divisor = 1_000_000_000u64;
    while kappa > 0 {
        let digit = integer / divisor;
        if digit != 0 || !digits.is_empty() {
            digits.push(b'0' + digit as u8);
        }
        integer -= digit * divisor;
        kappa -= 1;
        let remainder = (integer << shift) + fraction;
        if remainder <= delta {
            round_digit(&mut digits, delta, remainder, divisor << shift, distance);
            return (
                String::from_utf8(digits).expect("decimal digits"),
                -decimal_exponent + kappa,
            );
        }
        divisor /= 10;
    }
    let mut unit = 10u64;
    loop {
        fraction *= 10;
        delta *= 10;
        kappa -= 1;
        let digit = fraction >> shift;
        if digit != 0 || !digits.is_empty() {
            digits.push(b'0' + digit as u8);
        }
        fraction &= one - 1;
        if fraction < delta {
            // Preserve the upstream uint64_t arithmetic in the final rounding
            // distance; do not let debug/release overflow behavior diverge.
            round_digit(
                &mut digits,
                delta,
                fraction,
                one,
                distance.wrapping_mul(unit),
            );
            return (
                String::from_utf8(digits).expect("decimal digits"),
                -decimal_exponent + kappa,
            );
        }
        unit *= 10;
    }
}
