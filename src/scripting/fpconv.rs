#[derive(Clone, Copy)]
struct Fp {
    fraction: u64,
    exponent: i32,
}

impl Fp {
    fn normalized(mut self) -> Self {
        let shift = self.fraction.leading_zeros();
        self.fraction <<= shift;
        self.exponent -= shift as i32;
        self
    }

    fn multiply(self, other: Self) -> Self {
        // Exact 128-bit product replaces the original four 32-bit partial
        // products, with the same rounding of the low 64 bits.
        let product = u128::from(self.fraction) * u128::from(other.fraction);
        Self {
            fraction: ((product + (1u128 << 63)) >> 64) as u64,
            exponent: self.exponent + other.exponent + 64,
        }
    }
}

